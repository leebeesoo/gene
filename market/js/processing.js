const clean = (s) => String(s || '').replace(/\s+/g, '');

/** 품목 이름(예: 월동무, 풋고추, 겨울대파) → 가공 정보 */
export function procFor(item) {
  const n = clean(item);
  if (!n) return null;
  const exact = PROCESSING.find((p) => p.id === n || (p.alias || []).includes(n));
  if (exact) return exact;
  // 접미 일치: 가장 긴 이름부터 (양배추가 배추로 잡히지 않게)
  const keys = PROCESSING.flatMap((p) => [p.id, ...(p.alias || [])].map((k) => [k, p])).sort((a, b) => b[0].length - a[0].length);
  const hit = keys.find(([k]) => k.length >= 1 && n.endsWith(k));
  return hit ? hit[1] : null;
}
