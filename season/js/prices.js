// KAMIS 평년 산식: 해당 연도 직전 5년 같은 달 값 중 최고·최저를 뺀 3년 평균.
// 5년 값이 모두 있어야 계산(아니면 null).
export function normalOf(p, year, month) {
  const vals = [];
  for (let y = year - 5; y < year; y++) {
    const v = p.y[y]?.[month - 1];
    if (v == null) return null;
    vals.push(v);
  }
  vals.sort((a, b) => a - b);
  return Math.round((vals[1] + vals[2] + vals[3]) / 3);
}

export const valueAt = (p, year, month) => p.y[year]?.[month - 1] ?? null;

// 기준월부터 거슬러 n개월 시계열 [{y, m, v, nv}]
export function series(p, n = 22, [by, bm] = PRICE_META.baseYM) {
  const out = [];
  let y = by, m = bm;
  for (let i = 0; i < n; i++) {
    out.unshift({ y, m, v: valueAt(p, y, m), nv: normalOf(p, y, m) });
    m--; if (m === 0) { m = 12; y--; }
  }
  return out;
}

// 품목별 요약: 기준월(없으면 올해 가장 최근 조사월) 값, 평년, 전년
export function summary(p) {
  let [y, m] = PRICE_META.baseYM;
  let v = valueAt(p, y, m);
  let back = 0;
  while (v == null && back < 9) { m--; if (m === 0) { m = 12; y--; } v = valueAt(p, y, m); back++; }
  if (v == null) return null;
  const nv = normalOf(p, y, m);
  const pv = valueAt(p, y - 1, m);
  return {
    y, m, v, nv, pv, stale: back > 0,
    vsNormal: nv ? (v - nv) / nv : null,
    vsPrev: pv ? (v - pv) / pv : null,
  };
}
